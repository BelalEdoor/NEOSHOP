# ── سير عمل "المنتج المُرجَع" (B→A — العميل أخرج منتجاً من السلة) ───────────────
# كم ثانية ننتظر بصمت بعد لحظة الخروج قبل التحذير — نافذة تسمح للعميل
# بحذف المنتج من الفاتورة يدوياً بعد إخراجه مباشرة (أو كان حذفه أصلاً قبلها).
