"""
cv/config.py
============
إعدادات ثابتة لنظام كشف السرقة — مكان واحد لتعديل كل القيم القابلة للتغيير.

CAMERA LAYOUT
-------------
    ┌────────────────────────────┐
    │                            │  <- ZONE 1 (top 45%)
    │   ZONE 1 : scan zone       │     يد + منتج يظهران هنا أولاً،
    │                            │     قبل النزول إلى السلة
    ├────────────────────────────┤  <- boundary at y = ZONE_BOUNDARY * frame_height
    │                            │
    │   ZONE 2 : cart basket     │  <- ZONE 2 (bottom 55%)
    │   (settle zone)            │     المنتج يستقر هنا
    │                            │
    └────────────────────────────┘

نموذج YOLO: يُقرأ مساره من core.config.settings.YOLO_MODEL_PATH (لا يُكرَّر هنا).
"""

# ── Zone geometry (fraction of frame height, 0.0 = top, 1.0 = bottom) ─────────
ZONE_BOUNDARY = 0.45  # أعلى 45% = Zone 1 (منطقة المسح)، الباقي = Zone 2 (السلة)

ZONE_1_NAME = "scan"
ZONE_2_NAME = "cart"

# ── Detection ──────────────────────────────────────────────────────────────────
CONFIDENCE_THRESHOLD = 0.45   # أقل ثقة YOLO تُعتبر اكتشافاً حقيقياً
IOU_MATCH_THRESHOLD  = 0.35   # IoU المطلوب لربط اكتشاف بكائن متتبَّع من الإطار السابق

# ── Hand detection (MediaPipe Hands) ────────────────────────────────────────────
# اليد لم تعد تُستنتَج من فئة COCO "person" (بديل خام وغير دقيق) — تُكتشف الآن
# مباشرة عبر MediaPipe Hands، فتُشغَّل مع YOLO على كل إطار في detector.py.
HAND_DETECTION_CONFIDENCE = 0.6
HAND_TRACKING_CONFIDENCE  = 0.5
MAX_HANDS = 4

# نسبة تمدُّد صندوق المنتج (نسبةً لأبعاده) عند فحص قرب اليد منه — "قريب/ملموس"
# وليس تطابقاً بكسلياً دقيقاً، لأن صندوق اليد (MediaPipe) وصندوق المنتج (YOLO)
# يأتيان من نموذجين مختلفين ونادراً ما يتطابقان تماماً حتى أثناء الإمساك الفعلي.
HAND_PRODUCT_PROXIMITY_MARGIN = 0.25

# ── Theft decision logic ───────────────────────────────────────────────────────
# زمني: منتج في Zone 1 لأكثر من هذه المدة دون مسح → تحذير مبكر (PROLONGED_HOLDING)
ZONE1_TIME_THRESHOLD = 4.0

# مكاني: عدد الإطارات المتتالية التي يجب أن يظهر فيها المنتج داخل Zone 2 قبل
# اعتباره "مستقراً" (settled). يمنع الإنذارات الكاذبة من رجفة/حركة يد عابرة.
SETTLE_FRAMES_REQUIRED = 5

# نافذة زمنية (ثواني): يجب أن يكون هناك مسح مسجَّل خلالها قبل استقرار المنتج
# في Zone 2 حتى يُعتبر "مدفوعاً". لا مسح خلال هذه النافذة → تنبيه (UNSCANNED_IN_CART).
SCAN_MATCH_WINDOW_SECONDS = 6.0

# فترة التهدئة بين التنبيهات المتكررة لنفس الجلسة (يمنع إغراق النظام بالتنبيهات).
ALERT_COOLDOWN = 8.0

# ── Product classes ──────────────────────────────────────────────────────────────
# هذه أسماء فئات حقيقية من نموذجنا المدرَّب (backend/models/best.pt)، وليست
# فئات COCO بديلة — يجب أن تطابق تماماً قائمة `names:` في data.yaml المستخدم
# أثناء التدريب (وإلا يتجاهل detector.py الفئة بصمت لعدم مطابقتها). أي فئة
# جديدة تُضاف في تدريب لاحق يجب إضافتها هنا أيضاً.
PRODUCT_CLASSES = {
    "bottle", "candy", "chips", "chocolate", "nuts", "pasta",
}

# فئة احتياطية فقط لنموذج مخصَّص قد يُخرِج فئة "hand" حرفية لاحقاً — الكشف
# الفعلي عن اليد الآن يأتي من MediaPipe (انظر أعلاه)، وليس من فئات YOLO/COCO.
HAND_CLASSES = {"hand"}
