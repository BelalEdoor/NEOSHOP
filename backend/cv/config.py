# دقة الاستدلال لـ YOLO (imgsz بالبكسل). كانت 960 ثابتة داخل detector.py —
# صارت هنا مركزية وقابلة للتعديل. الفرق العملي بسيط جداً للمنتجات الكبيرة
# نسبياً (زجاجة/كيس شيبس) لكن الفرق بزمن الاستدلال على CPU كبير جداً:
# 960px تقريباً ٢-٣× أبطأ من 640px على نفس المعالج بدون أي تسريع GPU حقيقي.
# 480 خطوة إضافية للسرعة — لا يزال كافياً تماماً لصناديق بحجم منتج داخل الإطار.
YOLO_IMGSZ = 480

# أقصى عدد صناديق يعيدها YOLO لكل إطار. المشهد هنا "منتج واحد أو اثنين + يد"
# عملياً، لا داعي إطلاقاً للقيمة الافتراضية 20 — تقليلها يخفّف NMS ومعالجة
# ما بعد الاستدلال (post-processing) بشكل طفيف لكن مجاني تماماً.
YOLO_MAX_DETECTIONS = 10

# كل كم إطار وارد فعلياً يُشغَّل عليه YOLO (كشف المنتجات — حرِج للقرار).
# القرار بالثواني (GRACE_PERIOD=2s، SCAN_TIMEOUT=8s) وليس بعدد الإطارات، فتقليل
# معدّل التحليل الفعلي لا يغيّر دقة القرار عملياً لكنه يخفّض حِمل المعالج كثيراً.
# اجعلها 1 لتعطيل التخطي بالكامل.
ANALYZE_EVERY_N_FRAMES = 3

# كل كم إطار *وارد* (وليس "محلَّل") يُشغَّل عليه MediaPipe (كشف اليد).
# ⚠️ اليد غير مستخدَمة إطلاقاً في قرار السرقة الفعلي (theft_logic.py/tracker.py
# لا يعتمدان عليها — تحقّق: grep لا يُظهر أي استخدام لـ category=="hand" في
# أي منهما) — دورها الوحيد حالياً هو العرض التجميلي بأداة المعاينة
# (cv/preview.py). لذلك تشغيلها أندر بكثير من كشف المنتجات آمن تماماً ولا
# يؤثر على دقة الكشف أو الفرملة. اجعلها مساوية لـ ANALYZE_EVERY_N_FRAMES
# لتشغيلها بنفس معدّل المنتجات، أو 1 لتعطيل التخطي الإضافي.
HAND_ANALYZE_EVERY_N_FRAMES = 6

# ── Hand detection (MediaPipe Hands) ────────────────────────────────────────────
# اليد لم تعد تُستنتَج من فئة COCO "person" (بديل خام وغير دقيق) — تُكتشف الآن
# مباشرة عبر MediaPipe Hands، فتُشغَّل مع YOLO على كل إطار في detector.py.
# القيم أدناه أكثر مرونة لتشغيل الكاميرا العادية دون الحاجة إلى وضع يد مثالي.
HAND_DETECTION_CONFIDENCE = 0.35
HAND_TRACKING_CONFIDENCE  = 0.25
MAX_HANDS = 2

# تعقيد نموذج MediaPipe Hands: 0 = أخف وأسرع بكثير (وأقل دقة شكل اليد
# الدقيقة قليلاً)، 1 = الافتراضي الأثقل. صندوق اليد التقريبي (المستخدَم هنا
# فقط لتحديد الموقع، لا لتفاصيل الأصابع) لا يتأثر عملياً — استخدم 0 على أي
# جهاز بدون GPU حقيقي.
MEDIAPIPE_MODEL_COMPLEXITY = 0

# نسبة تمدُّد صندوق المنتج (نسبةً لأبعاده) عند فحص قرب اليد منه — "قريب/ملموس"
# وليس تطابقاً بكسلياً دقيقاً، لأن صندوق اليد (MediaPipe) وصندوق المنتج (YOLO)
# يأتيان من نموذجين مختلفين ونادراً ما يتطابقان تماماً حتى أثناء الإمساك الفعلي.
HAND_PRODUCT_PROXIMITY_MARGIN = 0.25

# ── Theft decision logic ───────────────────────────────────────────────────────
# زمني: منتج في Zone 1 لأكثر من هذه المدة دون مسح → تحذير مبكر (PROLONGED_HOLDING)
ZONE1_TIME_THRESHOLD = 4.0

# مكاني: عدد الإطارات المتتالية التي يجب أن يظهر فيها المنتج داخل Zone 2 قبل
# اعتباره "مستقراً" (settled). يمنع الإنذارات الكاذبة من رجفة/حركة يد عابرة.
SETTLE_FRAMES_REQUIRED = 5

# نافذة زمنية (ثواني): يجب أن يكون هناك مسح مسجَّل خلالها قبل استقرار المنتج
# في Zone 2 حتى يُعتبر "مدفوعاً". لا مسح خلال هذه النافذة → تنبيه (UNSCANNED_IN_CART).
SCAN_MATCH_WINDOW_SECONDS = 6.0

# فترة التهدئة بين التنبيهات المتكررة لنفس الجلسة (يمنع إغراق النظام بالتنبيهات).
ALERT_COOLDOWN = 8.0

# ── مهل سير عمل "المنتج المعلّق" (theft_logic.py) ──────────────────────────────
# كم ثانية يبقى المنتج داخل Zone B قبل أن نبدأ بإزعاج العميل أصلاً — نافذة
# صغيرة تسمح للعميل بمسح المنتج بشكل طبيعي بعد وضعه مباشرةً.
GRACE_PERIOD = 2.0

# ⏱️ المهلة المعروضة على شاشة نقطة البيع لإعادة مسح المنتج (٨ ثوانٍ).
