"""
cv/log_colors.py
=================
ألوان ANSI لتمييز سجلات الرؤية الحاسوبية بالطرفية — لتسهيل المتابعة أثناء
التطوير والتصحيح (اكتشاف منتج، تحذير، تفعيل فرامل، تحريرها...).

آمن تماماً في كل مكان: لو الطرفية أو مجمّع اللوقز (ملف، systemd journal،
Docker logs...) لا يدعم ANSI، الرموز بتظهر كنص خام إضافي بدون أي كسر
بالتنسيق ولا أي استثناء — لا تعتمد عليها أي منطق آخر بالكود.
"""

RESET = "\033[0m"
BOLD = "\033[1m"

GREEN = "\033[92m"    # نجاح / تحرير فرامل
YELLOW = "\033[93m"   # تحذير (الرجاء المسح)
RED = "\033[91m"      # خطر / تفعيل فرامل
CYAN = "\033[96m"     # اكتشاف منتج (معلومة عادية)
MAGENTA = "\033[95m"  # تشخيص/معلومات WebSocket
GRAY = "\033[90m"


def colorize(text: str, color: str, bold: bool = False) -> str:
    prefix = BOLD if bold else ""
    return f"{prefix}{color}{text}{RESET}"
