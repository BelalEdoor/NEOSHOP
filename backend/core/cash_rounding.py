"""
core/cash_rounding.py
======================
تقريب "نقدي" (Cash Rounding) — المبلغ الذي تطلبه آلة الدفع من العميل نقداً،
مقرَّب لأقرب شيكل صحيح، لأن الآلة لا تملك فيزيائياً أي عملة/ورقة أصغر من
1 شيكل (لا "أغورات"/قروش). سعر الفاتورة (Invoice.total_amount) يبقى دقيقاً
بكسوره للسجلات والتقارير — هذا التقريب يُطبَّق فقط لحظة تحديد المبلغ الذي
تطلبه آلة الدفع فعلياً من العميل (Payment.total_due).

──────────────────────────────────────────────────────────────────────────
لماذا هذا الملف ضروري؟ (خلفية المشكلة التي يُصلحها)
──────────────────────────────────────────────────────────────────────────
قبل هذا الإصلاح كان total_due يُرسَل للـ ESP32 كما هو بكسوره (مثال: فاتورة
12.48 شيكل). كل العملات/الأوراق المقبولة (1، 2، 5، 10، 20، 50...) أعداد
صحيحة، فكان "الباقي" (change) دائماً كسرياً تقريباً، وكان الـ ESP32 يقرّبه
بـ (int)round(change) *بعد* استلام النقود فعلياً — أي في اللحظة الخطأ.
هذا كان يُفقد أو يُضيف حتى 0.5 شيكل بصمت في كل عملية دفع تقريباً، دون أي
سجل لهذا الفرق.

الإصلاح: نقرّب المبلغ المطلوب *قبل* ما يوصل للـ ESP32 أصلاً (Swedish /
Cash Rounding)، بدل ما يوصله بكسوره وترجع المشكلة تظهر لاحقاً وقت حساب
"الباقي" فعلياً على الجهاز نفسه.
"""
from decimal import Decimal, ROUND_HALF_UP


def round_to_cash_unit(amount: float, unit: float = 1.0) -> float:
    """
    يقرّب `amount` لأقرب مضاعف لـ `unit` (افتراضياً 1 شيكل — أصغر عملة
    فيزيائية تقبلها آلة الدفع حالياً) باستخدام "نصف لأعلى" (ROUND_HALF_UP)،
    وهو أكثر توقّعاً للمستخدم من التقريب المصرفي الافتراضي بـ Python
    (banker's rounding) الذي قد يقرّب 0.5 لأسفل أحياناً بشكل غير متوقَّع.

    نستخدم Decimal (مش round() العادية) لتفادي أخطاء تمثيل الفاصلة
    العائمة (مثال: round(2.675, 2) بـ Python العادي قد لا يعطي 2.68
    كما هو متوقَّع رياضياً بسبب طريقة تمثيل الأعداد العشرية بالـ binary).
    """
    if unit <= 0:
        return round(amount, 2)

    d_amount = Decimal(str(amount))
    d_unit = Decimal(str(unit))
    steps = (d_amount / d_unit).quantize(Decimal("1"), rounding=ROUND_HALF_UP)
    return float(steps * d_unit)